import { test, expect, _electron as electron, type ElectronApplication } from '@playwright/test';
import path from 'node:path';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import { spawn, type ChildProcess } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';

const root=path.resolve(__dirname,'..');
const version=JSON.parse(readFileSync(path.join(root,'package.json'),'utf8')).version;
const executable=path.join(root,'release',`GAL-Agent-${version}`,'GAL Agent.exe');

test('packaged app starts its frozen backend, captures fixture and resumes saved session',async()=>{
  test.skip(!existsSync(executable),'Build the Windows app first.');
  const directory=path.join(root,'test-results','packaged-'+crypto.randomUUID());
  await fs.mkdir(directory,{recursive:true});
  const env={...process.env,GAL_AGENT_DATA_DIR:path.join(directory,'data'),GAL_AGENT_SHELL_DATA_DIR:path.join(directory,'shell')};
  delete env.ELECTRON_RUN_AS_NODE;
  let app:ElectronApplication|undefined;
  let fixture:ChildProcess|undefined;
  try{
    fixture=spawn(path.join(root,'.venv','Scripts','python.exe'),[path.join(root,'tests','native_smoke.py'),'--fixture',directory],{windowsHide:true,stdio:['ignore','pipe','pipe']});
    const identity=await new Promise<{hwnd:number;pid:number}>((resolve,reject)=>{
      let text='';const timer=setTimeout(()=>reject(new Error('Fixture startup timeout')),10000);
      fixture!.stdout!.on('data',chunk=>{text+=chunk.toString();if(text.includes('\n')){clearTimeout(timer);resolve(JSON.parse(text.split('\n')[0]));}});
      fixture!.on('error',reject);
    });
    app=await electron.launch({executablePath:executable,args:[],env,timeout:45000});
    let page=await app.firstWindow();
    await expect(page.getByText('本地会话已就绪')).toBeVisible({timeout:40000});
    expect(await app.evaluate(({app})=>app.isPackaged)).toBe(true);
    expect(await app.evaluate(({app})=>app.getVersion())).toBe(version);
    const health=await page.evaluate(async()=>(await window.gal!.api('GET','/health')).data);
    expect(health.version).toBe(version);
    expect(health.agent_framework).toBe('langchain');
    // 从实际 asar 资源加载看板娘，避免源码可见而独立应用缺图。
    await page.locator('.welcome-mascot-image').evaluate((image:HTMLImageElement)=>image.decode());
    await page.screenshot({path:path.join(root,'test-results','welcome-mascot-packaged.png')});
    await page.getByRole('button',{name:'新建会话',exact:true}).click();
    await page.getByLabel('会话名称').fill('打包版 · 恢复测试');
    await page.getByRole('button',{name:'创建会话'}).click();
    await page.getByRole('button',{name:'选择窗口',exact:true}).first().click();
    const picker=page.getByRole('dialog',{name:'选择游戏窗口'});
    await picker.getByRole('button',{name:/GAL Agent Native Test Fixture/}).click();
    await expect(page.getByAltText('当前选定的游戏窗口')).toBeVisible({timeout:15000});
    const state=await page.evaluate(async()=> (await window.gal!.api('GET','/state')).data);
    expect(state.window.hwnd).toBe(identity.hwnd);
    expect(state.window.pid).toBe(identity.pid);
    await page.getByRole('button',{name:'操作设置',exact:true}).click();
    const profileDialog=page.getByRole('dialog',{name:'游戏操作设置'});
    await expect(profileDialog.getByLabel('画面稳定最长等待（毫秒）')).toHaveCount(0);
    await expect(profileDialog.getByLabel('文字稳定等待（毫秒）')).toHaveCount(0);
    await expect(profileDialog.getByLabel('操作间隔（毫秒）')).toBeVisible();
    await expect(profileDialog.getByLabel('原剧情最多重试次数')).toHaveAttribute('max','2');
    await profileDialog.locator('select').first().selectOption('CLICK');
    const calibration=profileDialog.getByRole('button',{name:'在游戏预览中标记推进位置',exact:true});
    await calibration.scrollIntoViewIfNeeded();
    const box=await calibration.boundingBox();
    expect(box).not.toBeNull();
    await calibration.click({position:{x:box!.width*.45,y:box!.height*.8}});
    await profileDialog.getByRole('button',{name:'保存设置',exact:true}).click();
    const savedProfile=await page.evaluate(async()=>{
      const current=(await window.gal!.api('GET','/state')).data;
      return (await window.gal!.api('GET',`/sessions/${current.session_id}`)).data.settings.profile;
    });
    expect(savedProfile.advance_key).toBe('CLICK');
    expect(savedProfile.advance_point[0]).toBeCloseTo(.45,2);
    expect(savedProfile.advance_point[1]).toBeCloseTo(.8,2);
    expect(savedProfile.input_hold_ms).toBe(100);
    await page.getByRole('button',{name:'添加模型配置',exact:true}).click();
    const configDialog=page.getByRole('dialog',{name:'添加模型配置'});
    await configDialog.getByLabel('配置名称',{exact:true}).fill('悬浮窗控制测试');
    await configDialog.getByLabel('API URL',{exact:true}).fill('http://127.0.0.1:9/v1');
    await configDialog.getByLabel('模型名称',{exact:true}).fill('fixture-vision');
    await configDialog.getByRole('button',{name:'保存配置',exact:true}).click();
    await page.getByRole('button',{name:'悬浮窗',exact:true}).click();
    await expect.poll(()=>app!.windows().length).toBe(2);
    const overlay=app.windows()[1];
    await expect(overlay.getByRole('button',{name:'开始',exact:true})).toBeEnabled();
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>!w.webContents.getURL().endsWith('#overlay'))!.focus());
    await overlay.getByRole('button',{name:'开始',exact:true}).click();
    await expect(overlay.getByRole('region',{name:'运行控制'})).toContainText('请切回游戏窗口');
    await expect(overlay.getByRole('button',{name:'继续',exact:true})).toBeDisabled();
    expect(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().endsWith('#overlay'))!.isFocusable())).toBe(false);
    await overlay.getByRole('button',{name:'暂停 / 接管',exact:true}).click();
    await expect(overlay.getByRole('button',{name:'继续',exact:true})).toBeEnabled();
    const afterPause=await page.evaluate(async()=>(await window.gal!.api('GET','/state')).data);
    expect(afterPause.status).toBe('paused');
    await page.getByRole('button',{name:'恢复进度',exact:true}).click();
    await page.getByRole('button',{name:'保存检查点',exact:true}).click();
    await page.getByLabel('备注（可选）').fill('游戏存档 1 · 模拟窗口');
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await expect(page.getByText('游戏存档 1 · 模拟窗口',{exact:true})).toBeVisible();
    await page.screenshot({path:path.join(root,'test-results','packaged-window.png')});
    await app.close();app=undefined;
    app=await electron.launch({executablePath:executable,args:[],env,timeout:45000});
    page=await app.firstWindow();
    await expect(page.getByText('本地会话已就绪')).toBeVisible({timeout:40000});
    await expect(page.getByRole('heading',{name:'打包版 · 恢复测试',exact:true})).toBeVisible();
    await expect(page.getByText('继续前，核对游戏进度')).toBeVisible();
    const restarted=await page.evaluate(async()=> (await window.gal!.api('GET','/state')).data);
    expect(restarted.status).toBe('paused');expect(restarted.window).toBeNull();
    await page.getByRole('button',{name:'选择窗口',exact:true}).first().click();
    await page.getByRole('dialog',{name:'选择游戏窗口'}).getByRole('button',{name:/GAL Agent Native Test Fixture/}).click();
    await expect(page.getByAltText('当前选定的游戏窗口')).toBeVisible();
    await page.getByRole('button',{name:'悬浮窗',exact:true}).click();
    await expect.poll(()=>app!.windows().length).toBe(2);
    const resumedOverlay=app.windows()[1];
    await expect(resumedOverlay.getByRole('button',{name:'继续',exact:true})).toBeDisabled();
    await resumedOverlay.getByRole('button',{name:'收起悬浮窗',exact:true}).click();
    await expect(resumedOverlay.getByRole('button',{name:'确认进度对齐',exact:true})).toBeInViewport();
    expect(await resumedOverlay.locator('.overlay-buttons button').allTextContents()).toEqual(['暂停 / 接管','确认进度对齐','继续']);
    await resumedOverlay.getByRole('button',{name:'确认进度对齐',exact:true}).click();
    await expect(resumedOverlay.getByRole('button',{name:'继续',exact:true})).toBeEnabled();
    await expect(page.getByText('继续前，核对游戏进度')).toHaveCount(0);
  }finally{
    await app?.close().catch(()=>{});
    await fs.writeFile(path.join(directory,'fixture-stop'),'');
    if(fixture)await new Promise<void>(resolve=>{if(fixture!.exitCode!==null)return resolve();fixture!.once('exit',()=>resolve());setTimeout(()=>{fixture!.kill();resolve();},3000);});
  }
});
